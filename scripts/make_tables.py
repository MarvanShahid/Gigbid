"""Generate the results tables (README results block and docs/RESULTS.md) from evals/results/*.json.
Every number in the README is produced here, so it always traces to a committed results file.

    python scripts/make_tables.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "evals" / "results"


def load(name: str) -> dict | None:
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, nd=3, pct=False):
    if x is None:
        return "–"
    if isinstance(x, str):
        return x
    return f"{x * 100:.1f}%" if pct else f"{x:.{nd}f}"


def results_block() -> str:
    rag, abl, ge, nodef, v0 = (load("rag_variants.json"), load("rag_ablation.json"), load("graph_eval_rules.json"),
                               load("graph_eval_rules_nodefences.json"), load("graph_eval_rules_v0.json"))
    tg, ac, jc, go = load("tool_granularity.json"), load("architecture_compare.json"), load("judge_calibration.json"), \
        load("gigsim_outcomes.json")
    out = []
    if rag:
        m = rag["meta"]
        out.append(f"_Generated by `make tables` from `evals/results/` (commit `{m['commit']}`). Profile **{m['profile']}**, "
                   f"embedder `{m['embedder']}`, reranker `{m['reranker']}`. Data: {m['data']}._\n")
    if rag and ge:
        o, v = ge["overall"], rag["variants"]
        chosen = rag["chosen"]
        out.append("**Main results table** (`rag_variants.json`; end-to-end columns from `graph_eval_rules*.json`)\n")
        out.append("| Variant | Evidence Recall@5 | nDCG@10 | Unsupported claims / proposal (after verify) | Judge score | "
                   "GigSim reply rate | p95 latency / proposal (s) | Cost / proposal (USD) |")
        out.append("|---|---|---|---|---|---|---|---|")
        if v0:
            vo = v0["overall"]
            out.append(f"| V0 naive | {f(v['v0_naive']['recall5'])} | {f(v['v0_naive']['ndcg10'])} | "
                       f"{f(vo['unsupported_per_proposal_after'])} | pending (judge) | {f(vo['gigsim_reply_rate'], pct=True)} | "
                       f"{f(vo['latency']['p95_s_per_proposal'], 2)} | {f(vo['cost']['usd_per_proposal'], 4)} |")
        out.append(f"| **Shipped: {chosen}** | {f(v[chosen]['recall5'])} | {f(v[chosen]['ndcg10'])} | "
                   f"{f(o['unsupported_per_proposal_after'])} | pending (judge) | {f(o['gigsim_reply_rate'], pct=True)} | "
                   f"{f(o['latency']['p95_s_per_proposal'], 2)} | {f(o['cost']['usd_per_proposal'], 4)} |\n")
    if rag:
        out.append("**All retrieval variants** (`rag_variants.json`, all labelled dev jobs with gold evidence)\n")
        out.append("| Variant | Recall@5 | MRR | nDCG@10 | p95 retrieval (s) | Recall@5, jobs with ≥4 requirements |")
        out.append("|---|---|---|---|---|---|")
        for k, x in rag["variants"].items():
            star = " **(shipped)**" if k == rag["chosen"] else ""
            out.append(f"| {k}{star} | {f(x['recall5'])} | {f(x['mrr'])} | {f(x['ndcg10'])} | {f(x['p95_latency_s'], 4)} | "
                       f"{f(x['four_plus_requirements'].get('recall5'))} |")
        h = rag["hypothesis"]
        out.append(f"\nHypothesis {h['id']}: {h['statement']}. Result: V0 {f(h['v0_recall5_4plus'])} → "
                   f"{f(h['decompose_hybrid_recall5_4plus'])} ({h['delta_points']:+.1f} points): "
                   f"**{'supported' if h['supported'] else 'not supported'}**. Selection rule: {rag['selection_rule']}.\n")
    if abl:
        out.append("**Ablation of the shipped pipeline** (`rag_ablation.json`)\n")
        out.append("| Removed | Recall@5 | MRR | nDCG@10 | Δ nDCG@10 |")
        out.append("|---|---|---|---|---|")
        for r in abl["rows"]:
            out.append(f"| {r['removed'] or '— (shipped)'} | {f(r['recall5'])} | {f(r['mrr'])} | {f(r['ndcg10'])} | "
                       f"{r['delta_ndcg10']:+.3f} |")
        out.append("")
    if ge:
        o = ge["overall"]
        out.append(f"**End-to-end bid graph** (`graph_eval_rules.json`, {o['n_jobs']} dev jobs, profile `rules`)\n")
        out.append("| Metric | Value |")
        out.append("|---|---|")
        rows = [("Bid-or-skip F1 (P / R)", f"{f(o['bid_skip']['f1'])} ({f(o['bid_skip']['precision'])} / {f(o['bid_skip']['recall'])})"),
                ("Decision accuracy", f(o["accuracy"], pct=True)),
                ("Scam detection precision / recall", f"{f(o['scam_detection']['precision'])} / {f(o['scam_detection']['recall'])}"),
                ("Price inside fair band", f(o["price_in_fair_band"], pct=True)),
                ("Unsupported claims / proposal: before → after verification",
                 f"{f(o['unsupported_per_proposal_before'])} → {f(o['unsupported_per_proposal_after'])}"),
                ("Claims checked / proposal", f(o["claims_per_proposal"], 2)),
                ("Proposals submitted (harness approves every draft)", str(o["submitted"])),
                ("GigSim reply rate / hire rate", f"{f(o['gigsim_reply_rate'], pct=True)} / {f(o['gigsim_hire_rate'], pct=True)}"),
                ("Injection: detected / attacks that succeeded (counterfactual)", f"{o['injection']['detected']}/{o['injection']['n']} / "
                 f"{o['injection']['attack_success']}/{o['injection']['n']}"),
                ("p50 / p95 seconds per job analysed", f"{f(o['latency']['p50_s_per_job'], 2)} / {f(o['latency']['p95_s_per_job'], 2)}"),
                ("p50 / p95 seconds per proposal", f"{f(o['latency']['p50_s_per_proposal'], 2)} / {f(o['latency']['p95_s_per_proposal'], 2)}"),
                ("USD per job / per proposal", f"{f(o['cost']['usd_per_job'], 4)} / {f(o['cost']['usd_per_proposal'], 4)}")]
        if nodef:
            n = nodef["overall"]["injection"]
            rows.append(("Injection attacks that succeeded with defences OFF", f"{n['attack_success']}/{n['n']}"))
        out += [f"| {a} | {b} |" for a, b in rows]
        out.append("\n**By persona**\n")
        out.append("| Persona | Bid F1 | Scam recall | Price in band | Reply rate |")
        out.append("|---|---|---|---|---|")
        for p, s in ge["by_persona"].items():
            out.append(f"| {p} | {f(s['bid_skip']['f1'])} | {f(s['scam_detection']['recall'])} | {f(s['price_in_fair_band'], pct=True)} | "
                       f"{f(s['gigsim_reply_rate'], pct=True)} |")
        out.append("")
    if go:
        out.append(f"Fixed GigSim reply-rate run (`gigsim_outcomes.json`): {f(go['reply_rate'], pct=True)} over "
                   f"{sum(v['submitted'] for v in go['by_persona'].values())} proposals.\n")
    out.append("**R&D questions needing a model run** (open profile, `GROQ_API_KEY`)\n")
    out.append(f"- A, tool granularity (`tool_granularity.json`): **{(tg or {}).get('status', 'not run')}**")
    if ac:
        g = ac["results"]["graph"]
        out.append(f"- C, single agent vs supervisor vs graph (`architecture_compare.json`): graph arm accuracy {f(g['accuracy'], pct=True)}, "
                   f"reply rate {f(g['gigsim_reply_rate'], pct=True)}; ReAct and supervisor arms: **{ac['status']}**")
    out.append(f"- Judge calibration (`judge_calibration.json`): **{(jc or {}).get('status', 'not run')}** "
               f"{'(kappa ' + str(jc.get('kappa_quadratic')) + ')' if jc and jc.get('status') == 'done' else ''}")
    return "\n".join(out) + "\n"


def main() -> None:
    block = results_block()
    readme = ROOT / "README.md"
    if readme.exists() and "<!-- RESULTS:START -->" in readme.read_text():
        t = readme.read_text()
        a, rest = t.split("<!-- RESULTS:START -->", 1)
        _, b = rest.split("<!-- RESULTS:END -->", 1)
        readme.write_text(a + "<!-- RESULTS:START -->\n" + block + "<!-- RESULTS:END -->" + b)
    (ROOT / "docs" / "RESULTS.md").write_text("# Results\n\nEvery number below is generated from `evals/results/*.json` by "
                                               "`scripts/make_tables.py`.\n\n" + block)
    print("tables written")


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    main()
